import {Router} from 'express';
import rateLimit from 'express-rate-limit';
import * as controller from '../controllers/authController.js';
import {requireUser} from '../middlewares/auth.js';
export const authRoutes=Router();
authRoutes.use(rateLimit({windowMs:900000,limit:30,standardHeaders:'draft-8',legacyHeaders:false}));
authRoutes.post('/login',controller.login);authRoutes.post('/signup',controller.signup);
authRoutes.post('/refresh',controller.refresh);authRoutes.post('/logout',controller.logout);
authRoutes.post('/forgot-password',controller.forgotPassword);
authRoutes.post('/recovery',controller.recoverySession);
authRoutes.post('/reset-password',requireUser,controller.resetPassword);